#!/bin/bash
# Lightning AI studio (3+ GPUs), one shot: venv, veRL fork (hopd), dataset, checks.
# Everything lands under <repo>/scratch so the layout matches $SCRATCH/hopd on TACC.
#
#   git clone <H-OPD repo> ~/H-OPD && cd ~/H-OPD
#   bash setup/lightning_setup.sh
#   source scratch/env.sh
#   bash experiments/mopd/run_lightning.sh papercheck
set -euo pipefail

HOPD_HOME="${HOPD_HOME:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
export HOPD_HOME
export HOPD_SCRATCH="${HOPD_SCRATCH:-$HOPD_HOME/scratch}"
export HOPD_ROOT="$HOPD_SCRATCH"                 # install_ls6.sh venv parent
export HOPD_VENV="${HOPD_VENV:-$HOPD_SCRATCH/.venv}"
export HOPD_DATA_ROOT="${HOPD_DATA_ROOT:-$HOPD_SCRATCH/data}"
export HOPD_CKPT_ROOT="${HOPD_CKPT_ROOT:-$HOPD_SCRATCH/checkpoints}"
export HF_HOME="${HF_HOME:-$HOPD_SCRATCH/.cache/huggingface}"
export HOPD_ENV_SCRIPT=""                        # no TACC modules here
mkdir -p "$HOPD_SCRATCH" "$HOPD_DATA_ROOT" "$HOPD_CKPT_ROOT" "$HF_HOME"

if [[ -n "${SCRATCH:-}" ]]; then
    echo "WARN: \$SCRATCH is set ($SCRATCH); run_ls6.sh would treat this as TACC. Unset it on Lightning." >&2
fi

ngpu=0
command -v nvidia-smi >/dev/null 2>&1 && ngpu=$(nvidia-smi -L 2>/dev/null | wc -l | tr -d ' ')
echo "GPUs: $ngpu  (paper recipe needs 3: student / VL teacher / text teacher)"
nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv 2>/dev/null || true

# 1. venv + torch/vllm/transformers stack + veRL fork editable install.
#    install_ls6.sh only clones veRL when verl/.git is missing; bootstrap below
#    makes sure the checkout is on the hopd branch either way.
bash "$HOPD_HOME/setup/install_ls6.sh"
bash "$HOPD_HOME/setup/bootstrap_verl.sh"

# shellcheck disable=SC1091
source "$HOPD_VENV/bin/activate"

# 2. Paper patches that live in this repo (tracked) and are copied onto the
#    gitignored nested veRL. run_ls6.sh re-applies them at every job start.
OVERLAY="$HOPD_HOME/experiments/mopd/verl_overlay/verl/experimental"
if [[ -d "$OVERLAY" ]]; then
    cp -v "$OVERLAY/teacher_loop/teacher_manager.py" "$HOPD_HOME/verl/verl/experimental/teacher_loop/teacher_manager.py"
    cp -v "$OVERLAY/agent_loop/agent_loop.py" "$HOPD_HOME/verl/verl/experimental/agent_loop/agent_loop.py"
fi
python -c "from verl.experimental.teacher_loop.teacher_manager import tokenize_text_teacher_prompt; print('overlay OK')"

# 3. Dataset: train 55k (with paper text_prompt / [IMAGE DESCRIPTION]) + the
#    three eval parquets (MathVista-200, MathVerse-200, MathVision). ~9 GB.
if [[ -z "$(find "$HOPD_DATA_ROOT" -name 'mmfine_reason_sampled_55k_text_prompt.parquet' | head -1)" ]]; then
    export HF_HUB_ENABLE_HF_TRANSFER="${HF_HUB_ENABLE_HF_TRANSFER:-1}"
    python "$HOPD_HOME/download_data.py" --out_dir "$HOPD_DATA_ROOT"
fi
find "$HOPD_DATA_ROOT" -name '*.parquet' -not -path '*/mopd/*' -exec ls -lh {} \;

# 4. Checks that do not need a GPU job.
python "$HOPD_HOME/experiments/mopd/doctor.py"
python "$HOPD_HOME/experiments/mopd/test_hopd_mix.py"

# 5. Shell exports for later terminals (run_lightning.sh sources this too).
ENV_FILE="$HOPD_SCRATCH/env.sh"
cat >"$ENV_FILE" <<EOF
# generated by setup/lightning_setup.sh
export HOPD_HOME="$HOPD_HOME"
export HOPD_SCRATCH="$HOPD_SCRATCH"
export HOPD_VENV="$HOPD_VENV"
export HOPD_DATA_ROOT="$HOPD_DATA_ROOT"
export HOPD_CKPT_ROOT="$HOPD_CKPT_ROOT"
export HF_HOME="$HF_HOME"
export HOPD_ENV_SCRIPT=""
export SKIP_INSTALL=1
source "$HOPD_VENV/bin/activate"
EOF
echo
echo "OK. Next:"
echo "  source $ENV_FILE"
echo "  bash experiments/mopd/run_lightning.sh papercheck"
echo "  python3 experiments/mopd/watch.py --follow   # second terminal"
